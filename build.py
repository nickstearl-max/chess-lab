"""Prepare the iPhone app's data files.

    .venv\\Scripts\\python iphone_app\\build.py [--with-calibrated]

* templates/  -- the default (cburnett / lichess) piece set in the app's binary format; with
                 --with-calibrated also every set calibrated in the desktop app
                 (~/.ai_chess_lab/templates). Leave those out of the published app: they are
                 crops of a site's piece artwork, and phone screenshots calibrate better anyway.
* icons/      -- home-screen icons
* pieces.js   -- piece artwork for the board view
* sw.js       -- bumps the offline cache version so phones pick up the new files
* tests/fixtures/ -- the sample screenshots as raw RGBA for `node tests/run.mjs`
"""

from __future__ import annotations

import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

from chesslab.paths import SAMPLES_DIR, TEMPLATES_DIR  # noqa: E402
from chesslab.render.qt_image import ensure_gui_app  # noqa: E402
from chesslab.vision.templates import SQUARE_PX, TemplateSet  # noqa: E402

ICON_SVG = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" fill="#070b10"/>
  <g transform="translate(12 12)">
    <rect width="40" height="40" rx="2" fill="#56718a"/>
    <path fill="#c9d3dc" d="M0 0h10v10H0zM20 0h10v10H20zM10 10h10v10H10zM30 10h10v10H30zM0 20h10v10H0zM20 20h10v10H20zM10 30h10v10H10zM30 30h10v10H30z"/>
  </g>
  <path d="M22 47V27h20" fill="none" stroke="#39f58c" stroke-width="4.5" stroke-linecap="round" stroke-linejoin="round"/>
  <path d="M49 27l-8-5.6v11.2z" fill="#39f58c"/>
</svg>"""


def write_set(ts: TemplateSet, set_id: str, label: str, out_dir: Path) -> dict:
    """Binary layout per template: RGB (S*S*3) then alpha (S*S), uint8."""
    if ts.square_px != SQUARE_PX:
        raise ValueError(f"{set_id}: templates are {ts.square_px}px, expected {SQUARE_PX}")
    chunks = []
    for t in ts.templates:
        rgb = np.clip(np.round(t.bgr[:, :, ::-1]), 0, 255).astype(np.uint8)
        alpha = np.clip(np.round(t.alpha[:, :, 0] * 255), 0, 255).astype(np.uint8)
        chunks.append(rgb.tobytes() + alpha.tobytes())
    (out_dir / f"{set_id}.bin").write_bytes(b"".join(chunks))
    return {"id": set_id, "label": label, "file": f"templates/{set_id}.bin",
            "symbols": "".join(t.symbol for t in ts.templates)}


def build_templates(with_calibrated: bool) -> list[dict]:
    from chesslab.render.piece_assets import default_template_set

    out = HERE / "templates"
    out.mkdir(exist_ok=True)
    for old in out.glob("*.bin"):
        old.unlink()
    index = [write_set(default_template_set(), "default", "Default (lichess style)", out)]
    calibrated = sorted(TEMPLATES_DIR.glob("*.npz")) if with_calibrated and TEMPLATES_DIR.exists() else []
    for path in calibrated:
        safe = re.sub(r"[^A-Za-z0-9_-]+", "_", path.stem)
        index.append(write_set(TemplateSet.load(path), f"cal_{safe}", f"Calibrated: {path.stem}", out))
    (out / "index.json").write_text(json.dumps(index, indent=1), encoding="utf-8")
    return index


def build_icons() -> None:
    from PySide6.QtCore import QByteArray, QRectF
    from PySide6.QtGui import QImage, QPainter
    from PySide6.QtSvg import QSvgRenderer

    renderer = QSvgRenderer(QByteArray(ICON_SVG.encode()))
    (HERE / "icons").mkdir(exist_ok=True)
    for size in (180, 192, 512):
        img = QImage(size, size, QImage.Format.Format_ARGB32)
        p = QPainter(img)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        renderer.render(p, QRectF(0, 0, size, size))
        p.end()
        img.save(str(HERE / "icons" / f"icon-{size}.png"))
    (HERE / "icons" / "icon.svg").write_text(ICON_SVG, encoding="utf-8")


def build_pieces() -> None:
    import chess.svg

    pieces = {sym: re.sub(r'\s(id|class)="[^"]*"', "", svg) for sym, svg in chess.svg.PIECES.items()}
    (HERE / "pieces.js").write_text(
        "// Generated by build.py from python-chess (chess.svg.PIECES).\n"
        "// Piece artwork: cburnett, CC BY-SA 3.0 (https://commons.wikimedia.org/wiki/Category:SVG_chess_pieces).\n"
        f"export const PIECE_SVG = {json.dumps(pieces, indent=1)};\n", encoding="utf-8")


def build_fixtures() -> None:
    out = HERE / "tests" / "fixtures"
    out.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((SAMPLES_DIR / "manifest.json").read_text(encoding="utf-8"))
    for entry in manifest:
        img = cv2.imread(str(SAMPLES_DIR / entry["file"]), cv2.IMREAD_COLOR)
        rgba = cv2.cvtColor(img, cv2.COLOR_BGR2RGBA)
        name = Path(entry["file"]).stem
        (out / f"{name}.rgba.gz").write_bytes(gzip.compress(rgba.tobytes(), 6))
        entry["width"], entry["height"], entry["raw"] = img.shape[1], img.shape[0], f"{name}.rgba.gz"
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")


def bump_cache_version() -> str:
    """Hash every file the service worker caches, so a changed app replaces the cached one."""
    h = hashlib.sha256()
    for path in sorted(HERE.rglob("*")):
        if path.is_file() and "tests" not in path.parts and path.name != "sw.js" and path.suffix != ".py":
            h.update(path.relative_to(HERE).as_posix().encode())
            h.update(path.read_bytes())
    version = h.hexdigest()[:12]
    sw = HERE / "sw.js"
    if sw.exists():
        text = re.sub(r'const VERSION = "[^"]*";', f'const VERSION = "{version}";', sw.read_text(encoding="utf-8"))
        sw.write_text(text, encoding="utf-8")
    return version


def main() -> None:
    ensure_gui_app(headless=True)
    for entry in build_templates("--with-calibrated" in sys.argv[1:]):
        print(f"piece set  {entry['label']:32s} {len(entry['symbols'])} templates")
    build_icons()
    build_pieces()
    build_fixtures()
    print("cache version", bump_cache_version())


if __name__ == "__main__":
    main()
